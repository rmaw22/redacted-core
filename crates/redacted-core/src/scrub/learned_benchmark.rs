//! Scrub time with many learned secrets, before any limit on them is decided.
//! Timing only means something in release:
//! `REDACTED_LEARNED_BENCHMARK_REPORT=$PWD/docs/BENCHMARK-LEARNED.md cargo test --release -p redacted-core learned_scale_benchmark -- --ignored`

use std::fmt::Write;
use std::time::{Duration, Instant};

use super::Scrubber;
use super::tests::{clean_corpus, scrubber_with_learned};
use crate::config::LearnedSecret;
use crate::fake_secrets;
use crate::scrub::{derive_shape, learn};

const COUNTS: [usize; 6] = [0, 1, 10, 100, 500, 1000];
const SIZES: [(&str, usize); 3] = [("1 KB", 1 << 10), ("100 KB", 100 << 10), ("5 MB", 5 << 20)];

/// Exact-only, every tenth entry with an opted-in shape, and every entry shaped.
const MIXES: [(&str, usize); 3] = [("exact", 0), ("10% shape", 10), ("all shape", 1)];

/// `count` entries with spread lengths (16..48), so the length prefilter lets
/// through as many candidates as a real config would; every `shape_every`th one
/// opts into a shape (0 = none).
fn learned_entries(count: usize, shape_every: usize) -> Vec<LearnedSecret> {
    (0..count)
        .map(|i| {
            let value = format!("k{i}_{}", fake_secrets::alnum(16 + i % 32));
            let entry = learn(&format!("key_{i}"), &value).unwrap();
            let shape = if shape_every > 0 && i % shape_every == 0 {
                derive_shape(&value)
            } else {
                None
            };
            LearnedSecret { shape, ..entry }
        })
        .collect()
}

/// 1000 exact entries with lengths spread 8..300: nearly every candidate is hashed.
fn wide_length_entries() -> Vec<LearnedSecret> {
    (0..1000)
        .map(|i| learn(&format!("key_{i}"), &fake_secrets::alnum(8 + i % 292)).unwrap())
        .collect()
}

/// Building the scrubber, which the CLI hook does on every tool call.
fn build_section() -> String {
    let mut out = String::from(
        "## Building the scrubber\n\n\
         The CLI hook is a fresh process per tool call, so it pays this every time; \
         the extension builds once per settings change.\n\n\
         | Entries | Build |\n| --- | ---: |\n",
    );
    for (label, count, shape_every) in [
        ("none", 0, 0),
        ("1000 exact", 1000, 0),
        ("1000 shape", 1000, 1),
        ("5000 shape", 5000, 1),
    ] {
        let entries = learned_entries(count, shape_every);
        let start = Instant::now();
        std::hint::black_box(scrubber_with_learned(entries));
        writeln!(out, "| {label} | {} |", shown(start.elapsed())).unwrap();
    }
    out + "\n"
}

/// The clean corpus repeated to `size` bytes, cut at a char boundary.
fn text_of_size(size: usize) -> String {
    let corpus: String = clean_corpus().into_iter().map(|(_, text)| text).collect();
    let mut text = corpus.repeat(size / corpus.len() + 1);
    let mut end = size;
    while !text.is_char_boundary(end) {
        end -= 1;
    }
    text.truncate(end);
    text
}

/// The median of a few runs; fewer on large inputs so the run stays short.
fn median_scrub_time(scrubber: &Scrubber, text: &str) -> Duration {
    let runs = if text.len() > 1 << 20 { 3 } else { 15 };
    let mut times: Vec<Duration> = (0..runs)
        .map(|_| {
            let start = Instant::now();
            std::hint::black_box(scrubber.scrub(text));
            start.elapsed()
        })
        .collect();
    times.sort();
    times[runs / 2]
}

fn shown(time: Duration) -> String {
    let ms = time.as_secs_f64() * 1000.0;
    if ms < 10.0 {
        format!("{ms:.2} ms")
    } else {
        format!("{ms:.0} ms")
    }
}

/// A table of median scrub times: one row per `(N, entries)`, one column per text size.
fn timing_table(texts: &[(&str, String)], rows: Vec<(usize, Vec<LearnedSecret>)>) -> String {
    let header: Vec<&str> = texts.iter().map(|(label, _)| *label).collect();
    let mut out = format!(
        "| N | {} |\n| --- |{}\n",
        header.join(" | "),
        " ---: |".repeat(texts.len())
    );
    for (count, entries) in rows {
        let scrubber = scrubber_with_learned(entries);
        let cells: Vec<String> = texts
            .iter()
            .map(|(_, text)| shown(median_scrub_time(&scrubber, text)))
            .collect();
        writeln!(out, "| {count} | {} |", cells.join(" | ")).unwrap();
    }
    out + "\n"
}

#[test]
#[ignore = "timing; run in release, see the module docs"]
fn learned_scale_benchmark() {
    let texts: Vec<(&str, String)> = SIZES
        .iter()
        .map(|&(label, size)| (label, text_of_size(size)))
        .collect();
    let mut report = String::from(
        "# Learned secrets at scale\n\n\
         Median scrub time of the clean corpus, repeated to each size, with the default tiers \
         plus `N` learned entries. Generated by `learned_scale_benchmark` in \
         `crates/redacted-core/src/scrub/learned_benchmark.rs`; numbers are from one machine \
         and move between runs.\n\n\
         - Exact entries: once any is learned, every token is peeled into candidates, and each \
         candidate whose byte length equals a learned `len` is hashed. Cost follows the number \
         of distinct lengths, not of entries. These entries span 32 lengths, so from N = 32 on \
         they add no more cost.\n\
         - Shapes: one regex per entry, each starting with a literal prefix the regex engine \
         searches for directly.\n\n",
    );
    for (mix, shape_every) in MIXES {
        let rows = COUNTS
            .iter()
            .map(|&count| (count, learned_entries(count, shape_every)))
            .collect();
        report += &format!("## {mix}\n\n{}", timing_table(&texts, rows));
    }
    report += "## Worst case: lengths spread 8..300\n\n\
               1000 exact entries whose lengths cover most tokens, so nearly every candidate is hashed.\n\n";
    report += &timing_table(&texts, vec![(1000, wide_length_entries())]);
    report += &build_section();
    match std::env::var("REDACTED_LEARNED_BENCHMARK_REPORT") {
        Ok(path) => std::fs::write(path, report).unwrap(),
        Err(_) => println!("{report}"),
    }
}
